"""The action rules' generated docs: one command builds them all
(ADR-0216 rule 5 and rule 8; SHD-05-008, SHD-06-004, SHD-06-005).

``uv run action-rules-docs --write`` rebuilds three Markdown fragments from
the current move advice and the authored table:

* :data:`GENERATED_RULES` — the generated action rules and the conditional
  verdicts, for the measuring-CVD page ``action_rule_comparison.md``;
* :data:`COMPARISON` — the comparison of the authored rules at every valid
  position of one vendor, rule by rule, for the same page;
* :data:`AUTHORED_TABLE` — the rules table of
  ``docs/topics/other_uses/action_rules.md``, one row for each carried-over
  authored rule.

``--check`` exits 1 when a committed fragment differs from what the command
builds (SHD-05-009).  Building them walks the one-vendor chance model, which
takes seconds, so the docs build only includes the committed fragments and
never computes them.  Nobody edits a fragment by hand.
"""

from __future__ import annotations

import argparse
import sys
from collections.abc import Iterable, Mapping, Sequence
from functools import cache
from pathlib import Path

from vultron.core.scoring.potential_actions import Actions
from vultron.measure.action_rules.authored import authored_rules
from vultron.measure.action_rules.generated import (
    ConditionalVerdict,
    GeneratedRule,
    PositionKey,
    conditional_verdicts,
    generated_rules,
)
from vultron.measure.action_rules.model import (
    ACTION_MOVES,
    AuthoredRule,
    RulePattern,
    SourcePair,
    action_words,
    move_advice_desiderata,
)
from vultron.measure.action_rules.report import (
    ComparisonReport,
    ConditionalOutcome,
    RuleReport,
    comparison_report,
)

WRITE_COMMAND = "uv run action-rules-docs --write"
"""The command that rebuilds every fragment (SHD-05-008)."""

#: The repository root, which the fragments' paths are relative to.
ROOT = Path(__file__).resolve().parents[3]

GENERATED_RULES = Path("docs/topics/measuring_cvd/_generated_action_rules.md")
"""The generated rules and the conditional verdicts."""

COMPARISON = Path("docs/topics/measuring_cvd/_action_rule_comparison.md")
"""The comparison at every valid position of one vendor."""

AUTHORED_TABLE = Path("docs/topics/other_uses/_action_rules_table.md")
"""The rules table of the other-uses action rules page."""

_HEADER = f"""<!--
Generated by `{WRITE_COMMAND}` from move advice and the authored action rules (vultron/measure/action_rules/).
Do not edit by hand: change the advice or the rules, then re-run the command.
-->
"""

_NONE = "—"


def _cell(text: str) -> str:
    """*text* safe in a table cell: a pipe would end the cell."""
    return text.replace("|", r"\|")


def _table(header: Sequence[str], rows: Iterable[Sequence[str]]) -> str:
    lines = [
        f"| {' | '.join(header)} |",
        f"|{'|'.join('---' for _ in header)}|",
    ]
    lines.extend(f"| {' | '.join(_cell(c) for c in row)} |" for row in rows)
    return "\n".join(lines)


def _pattern(pattern: RulePattern) -> str:
    """*pattern* as Markdown: its CS part as code, then its other parts."""
    cs, _, rest = pattern.label.partition(" · ")
    return f"`{cs}`" + (f" · {rest}" if rest else "")


def _patterns(patterns: Sequence[RulePattern]) -> str:
    return "<br/>".join(_pattern(p) for p in patterns) or _NONE


def _position(key: PositionKey) -> str:
    return f"`{key.cs.name}` · RM {key.rm.name} · EM {key.em.name}"


def _role(role: str) -> str:
    return str(role).upper() if role != "any" else "any"


def generated_rules_markdown(
    rules: Sequence[GeneratedRule], conditionals: Sequence[ConditionalVerdict]
) -> str:
    """The generated rules, then the conditional verdicts, as Markdown."""
    rule_rows = [
        (
            f"`{r.move}`",
            _role(r.role),
            str(r.band),
            "forced: happens anyway" if r.forced else "",
            _patterns(r.patterns),
        )
        for r in rules
    ]
    conditional_rows = [
        (f"`{c.move}`", _role(c.role), _position(c.position), c.caveat)
        for c in conditionals
    ]
    return (
        f"{_HEADER}\n"
        "### Generated rules\n\n"
        f"{_table(('Move', 'Role', 'Band', 'Forced', 'Positions'), rule_rows)}"
        "\n\n### Conditional verdicts\n\n"
        f"{_table(('Move', 'Role', 'Position', 'Band by history'), conditional_rows)}\n"
    )


def _rule_name(report: RuleReport) -> str:
    return f"Rule {report.number}"


def _conditional_rows(
    report: RuleReport, conditionals: Iterable[ConditionalOutcome]
) -> list[tuple[str, ...]]:
    return [
        (
            _rule_name(report),
            report.rule.roles_label,
            report.rule.action_label,
            ("⚠️ " if c.flagged else "") + c.caveat,
            _position(c.position),
        )
        for c in conditionals
    ]


def _result_rows(
    reports: Iterable[RuleReport], flagged_only: bool
) -> list[tuple[str, ...]]:
    rows: list[tuple[str, ...]] = []
    for report in reports:
        for span in report.spans:
            if flagged_only and not span.outcome.flagged:
                continue
            flag = "⚠️ " if span.outcome.flagged else ""
            rows.append(
                (
                    _rule_name(report),
                    report.rule.roles_label,
                    report.rule.action_label,
                    flag + span.outcome.label,
                    _patterns(span.patterns),
                )
            )
        rows.extend(
            _conditional_rows(
                report,
                (
                    c
                    for c in report.conditionals
                    if c.flagged or not flagged_only
                ),
            )
        )
    return rows


def comparison_markdown(report: ComparisonReport) -> str:
    """The comparison, as Markdown: the flagged results, every result by
    rule, then the unclaimed moves."""
    header = ("Rule", "Roles", "Action", "Result", "Where")
    unclaimed_rows = [
        (
            f"`{u.move}`",
            "<br/>".join(
                [_pattern(p) for p in u.patterns]
                + [
                    f"{_position(c.position)}: {c.caveat}"
                    for c in u.conditionals
                ]
            ),
        )
        for u in report.unclaimed
    ]
    return (
        f"{_HEADER}\n"
        "### Rule disagreements and misplaced rules\n\n"
        f"{_table(header, _result_rows(report.rules, flagged_only=True))}"
        "\n\n### Every result, rule by rule\n\n"
        f"{_table(header, _result_rows(report.rules, flagged_only=False))}"
        "\n\n### Unclaimed moves\n\n"
        f"{_table(('Move', 'Where'), unclaimed_rows)}\n"
    )


def _latex_cs(cs: str) -> str:
    """A ``vfdpxa`` pattern in the page's math: ``...p..`` is
    ``$\\cdot \\cdot \\cdot p\\cdot \\cdot$``."""
    return (
        "$" + "".join(r"\cdot " if c == "." else c for c in cs).strip() + "$"
    )


def _authored_pattern(rule: AuthoredRule) -> str:
    _, _, rest = rule.pattern.label.partition(" · ")
    return _latex_cs(rule.pattern.cs) + (f"<br/>{rest}" if rest else "")


def _desiderata(rule: AuthoredRule) -> str:
    catalog = move_advice_desiderata()
    return ", ".join(catalog[d].notation for d in rule.desiderata) or _NONE


def _move(rule: AuthoredRule) -> str:
    """The move *rule* names, or the move its action is the first time its
    event happens."""
    if isinstance(rule.action, str):
        return f"`{rule.action}`"
    move = ACTION_MOVES.get(rule.action)
    return _NONE if move is None else f"`{move}`, the first time"


def _carried_action(rule: AuthoredRule, source: SourcePair) -> str:
    """The ``Actions`` member a carried-over *rule* names, or else its
    *source*'s, in words."""
    action = rule.action if isinstance(rule.action, Actions) else source.action
    return action_words(action)


def authored_table_markdown(rules: Sequence[AuthoredRule]) -> str:
    """One row for each carried-over rule of *rules*, numbered by its place
    in *rules*: its pattern, its source pattern, roles, action, reason,
    desiderata and move (SHD-06-005)."""
    rows = [
        (
            str(number),
            _authored_pattern(rule),
            _latex_cs(source.pattern),
            rule.roles_label,
            _carried_action(rule, source),
            rule.reason,
            _desiderata(rule),
            _move(rule),
        )
        for number, rule in enumerate(rules, start=1)
        if (source := rule.source) is not None
    ]
    header = (
        "#",
        "Pattern",
        "Carried over from",
        "Roles",
        "Action",
        "Reason",
        "Desiderata",
        "Move",
    )
    return f"{_HEADER}\n{_table(header, rows)}\n"


@cache
def built_fragments() -> Mapping[Path, str]:
    """Each fragment, by its path from the repository root, as the command
    builds it from the current move advice and authored table."""
    rules = authored_rules()
    return {
        GENERATED_RULES: generated_rules_markdown(
            generated_rules(), conditional_verdicts()
        ),
        COMPARISON: comparison_markdown(comparison_report()),
        AUTHORED_TABLE: authored_table_markdown(rules),
    }


def stale_fragments(root: Path = ROOT) -> list[Path]:
    """Each fragment under *root* that is missing or differs from what the
    command builds (SHD-05-009)."""
    return [
        path
        for path, text in built_fragments().items()
        if not (root / path).is_file()
        or (root / path).read_text(encoding="utf-8") != text
    ]


def write_fragments(root: Path = ROOT) -> list[Path]:
    """Write every fragment under *root*; return the paths written."""
    written = []
    for path, text in built_fragments().items():
        target = root / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")
        written.append(path)
    return written


def main(argv: list[str] | None = None) -> int:
    """``uv run action-rules-docs --check | --write [--root DIR]``."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if a committed fragment is stale",
    )
    mode.add_argument(
        "--write", action="store_true", help="rebuild every fragment"
    )
    parser.add_argument(
        "--root",
        type=Path,
        default=ROOT,
        help="the repository root the fragments are under",
    )
    args = parser.parse_args(argv)
    if args.write:
        for path in write_fragments(args.root):
            print(f"wrote {path}")
        return 0
    stale = stale_fragments(args.root)
    for path in stale:
        print(f"stale: {path}; run {WRITE_COMMAND}", file=sys.stderr)
    return 1 if stale else 0


