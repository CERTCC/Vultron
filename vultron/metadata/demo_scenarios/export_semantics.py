"""Export the semantic registry's vocabulary to a JSON artifact for ``ui/``.

The Log Replay demo names and phrases every case-ledger entry by its
``semanticType``.  It must not keep its own list of those names or its own
phrasing for them: ``SEMANTIC_REGISTRY`` is the single source, and
:mod:`vultron.demo.report` already renders its ``phrase`` templates
(DRPT-03-002, DRPT-03-005).  This module projects one row per registry entry,
in registry order, into ``ui/src/data/semantic_registry.json``:

- ``semanticType`` — the ``MessageSemantics`` value, which is the label a
  ledger entry carries.
- ``wire`` — the wire pattern summary, rendered by the same
  :func:`~vultron.metadata.msm.occasions.format_pattern` that writes the
  occasion table's ``send`` column, or ``null`` for a dispatcher fallback,
  which matches no pattern.
- ``phrase`` — the active-voice template with named slots (SE-07-001).

Why not the occasion table: ``vultron/metadata/msm/occasions.yaml`` is a
projection of the same registry, but it is keyed by occasion rather than by
entry, leaves out the dispatcher fallbacks, carries no phrase, and is marked
internal (#2959).  The UI would also need a YAML parser it does not have.
Both artifacts are generated from ``SEMANTIC_REGISTRY`` and share the wire
renderer, so neither restates the other's vocabulary.

The output is deterministic, so the drift test
``test/metadata/demo_scenarios/test_export_semantics.py`` fails when the
committed file differs from a fresh export.

Usage::

    uv run export-demo-semantics
"""

from collections.abc import Sequence
from typing import Any

from vultron.metadata.demo_scenarios.export_states import REPO_ROOT
from vultron.metadata.generated_files import serialize_json
from vultron.metadata.msm.occasions import format_pattern
from vultron.semantic_registry import SEMANTIC_REGISTRY
from vultron.semantic_registry._entry import SemanticEntry

#: Where the artifact lives, beside ``protocol_states.json``.
OUTPUT_PATH = REPO_ROOT / "ui" / "src" / "data" / "semantic_registry.json"

#: The command that regenerates the artifact, quoted in every hint.
REGEN_COMMAND = "uv run export-demo-semantics"


def entry_row(entry: SemanticEntry) -> dict[str, str | None]:
    """Project one registry entry onto the artifact's row shape."""
    return {
        "semanticType": entry.semantics.value,
        "wire": None
        if entry.pattern is None
        else format_pattern(entry.pattern),
        "phrase": entry.phrase,
    }


def build_payload(
    registry: Sequence[SemanticEntry] = SEMANTIC_REGISTRY,
) -> dict[str, Any]:
    """Build the full, deterministic export payload, in registry order."""
    return {
        "_README": (
            f"Generated by `{REGEN_COMMAND}` "
            "(vultron/metadata/demo_scenarios/export_semantics.py) from "
            "SEMANTIC_REGISTRY. Do not edit by hand; re-run the exporter and "
            "commit the result instead."
        ),
        "entries": [entry_row(entry) for entry in registry],
    }


def main() -> None:
    """Write the export to ``ui/src/data/semantic_registry.json``."""
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text(serialize_json(build_payload()), encoding="utf-8")
    print(f"Wrote {OUTPUT_PATH.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
