"""Generate the CSAF 2.1 models from the pinned local copy (CSAF-05-002, CSAF-05-003).

The CSAF schema references the CVSS, SSVC and extension schemas by URL. To
read the pinned local copy alone, regeneration stages the copy in a temporary
directory with every remote ``$ref`` rewritten to the staged file its pin
record maps the URL to, and runs ``datamodel-code-generator`` there with remote
references refused. A URL the pin record does not map is an
:class:`UnpinnedReferenceError`, never a download.

The staging puts the root schema at the top of the directory, because the
generator refuses a local reference outside its input file's directory once
remote references are refused.

``source`` and ``pin`` are arguments, so the draft-watch job can generate
models from an upstream checkout and compare them with the committed ones.

Usage::

    uv run csaf-models            # rewrite vultron/wire/csaf/models/
    uv run csaf-models --check    # exit 1 when the committed models are stale
"""

from __future__ import annotations

import argparse
import json
import posixpath
import subprocess
import sys
import warnings
from collections.abc import Iterator, Mapping, Sequence
from pathlib import Path, PurePosixPath
from tempfile import TemporaryDirectory

try:
    from datamodel_code_generator import InputFileType, generate
    from datamodel_code_generator.enums import DataModelType
    from datamodel_code_generator.format import Formatter, PythonVersion
except ImportError as exc:  # pragma: no cover - only without the dev group
    raise ImportError(
        "csaf-models needs the dev dependency group "
        "(datamodel-code-generator and ruff): run `uv sync --dev`"
    ) from exc

from vultron.metadata.base import repo_root
from vultron.metadata.csaf.pin import (
    MODELS_DIR,
    PIN_PATH,
    PINNED_COPY_DIR,
    CsafPin,
    load_pin,
)
from vultron.metadata.generated_files import stale_paths, write_generated

#: The keys that set a schema's base URI at its root. A remote base would make
#: the generator resolve the file's relative references against the network.
_BASE_URI_KEYS = ("$id", "id")

#: The two warnings every regeneration raises, both about limits of the models
#: that regeneration cannot change, so they are silenced rather than repeated:
#:
#: - An ``allOf`` base cannot follow ``$dynamicAnchor`` bindings. That is the
#:   JSON Schema meta-schemas the extension meta-schema extends, which describe
#:   an extension's schema, never a CSAF document's content.
#: - Pydantic takes no ``pattern`` on a URL or UUID field and no ``min_length``
#:   on a URL, so those constraints are dropped (a ``purl`` pattern among
#:   them). A document can pass the models and fail the schema there, one more
#:   reason a pass reads "schema-valid", never "valid CSAF" (CSAF-04-002).
_EXPECTED_WARNINGS = (
    r".*cannot follow the \$dynamicAnchor bindings.*",
    r".*is generated without th(is|ese) constraints?\.",
)


#: The first line of every generated module. Only a file that starts with it
#: is ever deleted, so a wrong ``--output`` cannot remove hand-written code.
GENERATED_MARKER = "# Generated by `uv run csaf-models`"


class UnpinnedReferenceError(ValueError):
    """A schema references a URL that the pin record maps to no local file."""


class ForeignModuleError(ValueError):
    """The output directory holds a module that ``csaf-models`` did not write."""


def schema_refs(node: object) -> Iterator[str]:
    """Yield every ``$ref`` string in the JSON schema *node*, depth first."""
    if isinstance(node, dict):
        for key, value in node.items():
            if key == "$ref" and isinstance(value, str):
                yield value
            else:
                yield from schema_refs(value)
    elif isinstance(node, list):
        for item in node:
            yield from schema_refs(item)


def _header(pin: CsafPin) -> str:
    return (
        f"{GENERATED_MARKER} from the pinned local copy of\n"
        f"# CSAF 2.1 draft {pin.draft_stage}, commit {pin.short_commit} of\n"
        f"# {pin.repository}.\n"
        "# Do not edit by hand (CSAF-05-003)."
    )


def resolve_relative_ref(target: str, origin: str) -> str:
    """Return the copy path a relative ``$ref`` *target* in *origin* names."""
    return posixpath.normpath(
        posixpath.join(posixpath.dirname(origin), target)
    )


def _rewrite_ref(ref: str, origin: str, location: str, pin: CsafPin) -> str:
    """Return *ref*, read in the pinned file *origin*, as seen from *location*.

    A same-document reference (``#/...``) is returned unchanged. Any other
    reference is resolved to a path inside the pinned local copy, through the
    pin record for a URL, and made relative to the staged file *location*.

    Raises:
        UnpinnedReferenceError: the reference names a URL the pin does not
            map, or a relative path that is not a file the pin lists.
    """
    target, hash_mark, fragment = ref.partition("#")
    if not target:
        return ref
    if "://" in target:
        try:
            local = pin.sources[target]
        except KeyError:
            raise UnpinnedReferenceError(
                f"{origin}: $ref {target!r} names no file in the pin record"
            ) from None
    else:
        local = resolve_relative_ref(target, origin)
        if local not in pin.sources.values():
            raise UnpinnedReferenceError(
                f"{origin}: $ref {target!r} resolves to {local!r}, "
                "which the pin record does not list"
            )
    staged = _staged_location(local, pin)
    relative = posixpath.relpath(staged, posixpath.dirname(location) or ".")
    return f"{relative}{hash_mark}{fragment}"


def _rewrite(node: object, origin: str, location: str, pin: CsafPin) -> object:
    """Return *node* with each ``$ref`` string rewritten by :func:`_rewrite_ref`."""
    if isinstance(node, dict):
        return {
            key: (
                _rewrite_ref(value, origin, location, pin)
                if key == "$ref" and isinstance(value, str)
                else _rewrite(value, origin, location, pin)
            )
            for key, value in node.items()
        }
    if isinstance(node, list):
        return [_rewrite(item, origin, location, pin) for item in node]
    return node


def _staged_location(local: str, pin: CsafPin) -> str:
    """Return where the pinned file *local* sits in the staging directory."""
    return PurePosixPath(pin.root).name if local == pin.root else local


def stage_pinned_copy(source: Path, staging: Path, pin: CsafPin) -> Path:
    """Write the schemas in *source* into *staging*, ready for the generator.

    Only the files the pin record lists are staged. Each loses its root base
    URI and has its references rewritten to staged files. Returns the staged
    root schema.

    Raises:
        UnpinnedReferenceError: a schema references a URL the pin does not map.
        FileNotFoundError: a file the pin record lists is missing from *source*.
    """
    for local in sorted(set(pin.sources.values())):
        location = _staged_location(local, pin)
        schema = json.loads((source / local).read_bytes())
        for key in _BASE_URI_KEYS:
            schema.pop(key, None)
        staged = _rewrite(schema, local, location, pin)
        write_generated(staging / location, json.dumps(staged, indent=2))
    return staging / _staged_location(pin.root, pin)


def render_models(
    source: Path = PINNED_COPY_DIR, pin: CsafPin | None = None
) -> dict[str, str]:
    """Return the generated models package as ``{relative path: source text}``.

    Reads *source* alone; any remote reference the pin does not map raises
    :class:`UnpinnedReferenceError` before the generator runs, and the
    generator itself refuses to fetch one.
    """
    pin = pin if pin is not None else load_pin()
    with TemporaryDirectory(prefix="csaf-models-") as staging:
        root = stage_pinned_copy(source, Path(staging), pin)
        with warnings.catch_warnings():
            for message in _EXPECTED_WARNINGS:
                warnings.filterwarnings(
                    "ignore", message=message, category=UserWarning
                )
            modules = generate(
                root,
                input_file_type=InputFileType.JsonSchema,
                output_model_type=DataModelType.PydanticV2BaseModel,
                target_python_version=PythonVersion.PY_312,
                formatters=[Formatter.BUILTIN],
                use_annotated=True,
                set_default_enum_member=True,
                use_double_quotes=True,
                allow_remote_refs=False,
                disable_timestamp=True,
                custom_file_header=_header(pin),
            )
    if not isinstance(modules, dict):
        raise TypeError(
            "datamodel-code-generator returned one module; the CSAF schema "
            "references other files, so a package was expected"
        )
    return {
        name: _ruff_clean(name, text)
        for name, text in (
            ("/".join(path), text) for path, text in sorted(modules.items())
        )
    }


def _ruff(args: Sequence[str], name: str, text: str) -> str:
    """Return *text* after ``ruff <args>``, read as the models module *name*."""
    root = repo_root()
    stdin_name = (MODELS_DIR / name).relative_to(root).as_posix()
    result = subprocess.run(
        [
            sys.executable,
            "-m",
            "ruff",
            *args,
            "--stdin-filename",
            stdin_name,
            "-",
        ],
        input=text,
        capture_output=True,
        text=True,
        cwd=root,
        check=False,
    )
    if result.returncode != 0:
        raise RuntimeError(
            f"ruff {args[0]} left findings in generated {name}:\n"
            f"{result.stdout}{result.stderr}"
        )
    return result.stdout


def _ruff_clean(name: str, text: str) -> str:
    """Apply the repository's ruff fixes and formatting to one generated module.

    The models are linted like every other tracked file (ADR-0094), so the
    committed text is the generator's output after ``ruff check --fix`` and
    ``ruff format``, under the repository's own ruff configuration.
    """
    fixed = _ruff(["check", "--fix", "--quiet"], name, text)
    return _ruff(["format", "--quiet"], name, fixed)


def stale_models(models: Mapping[str, str], output: Path) -> list[str]:
    """Return each module in *output* that differs from *models*, or is extra.

    A missing or changed module is stale, and so is a ``.py`` file in *output*
    that the generator no longer writes.
    """
    extra = (
        path.relative_to(output).as_posix()
        for path in output.rglob("*.py")
        if "__pycache__" not in path.parts
    )
    return sorted(
        set(stale_paths(output, models)) | (set(extra) - set(models))
    )


def write_models(models: Mapping[str, str], output: Path) -> list[str]:
    """Make *output* hold exactly *models*; return the paths that changed.

    Raises:
        ForeignModuleError: a ``.py`` file in *output* that this call would
            overwrite or delete does not start with :data:`GENERATED_MARKER`.
            Nothing is written, so a mistaken ``--output`` never replaces or
            deletes real code.
    """
    changed = stale_models(models, output)
    foreign = [
        path
        for path in changed
        if (output / path).is_file()
        and not (output / path)
        .read_text(encoding="utf-8")
        .startswith(GENERATED_MARKER)
    ]
    if foreign:
        raise ForeignModuleError(
            f"{output} holds modules csaf-models did not write: {foreign}"
        )
    for path in changed:
        if path in models:
            write_generated(output / path, models[path])
        else:
            (output / path).unlink()
    return changed


def _parse_args(argv: Sequence[str] | None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        prog="csaf-models", description=(__doc__ or "").split("\n\n")[0]
    )
    parser.add_argument(
        "--source",
        type=Path,
        default=PINNED_COPY_DIR,
        help="the directory holding the schemas (default: the pinned local copy)",
    )
    parser.add_argument(
        "--pin",
        type=Path,
        default=PIN_PATH,
        help="the pin record mapping URLs to files (default: %(default)s)",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=MODELS_DIR,
        help="the models package directory (default: %(default)s)",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="write nothing; exit 1 when the models in --output are stale",
    )
    return parser.parse_args(argv)


def main(argv: Sequence[str] | None = None) -> int:
    """Regenerate the CSAF models, or with ``--check`` report stale ones."""
    args = _parse_args(argv)
    models = render_models(args.source, load_pin(args.pin))
    if args.check:
        stale = stale_models(models, args.output)
        for path in stale:
            print(f"stale: {args.output / path}", file=sys.stderr)
        if stale:
            print("run `uv run csaf-models` to regenerate", file=sys.stderr)
        return 1 if stale else 0
    try:
        changed = write_models(models, args.output)
    except ForeignModuleError as exc:
        print(exc, file=sys.stderr)
        return 2
    for path in changed:
        print(f"wrote: {args.output / path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
