"""Generate the Protocol Specification's known-gaps fragment (DF-12-019).

The fragment lists, in three sections, each ``protocol`` and ``foundation``
requirement that the tests do not show ``main`` fully meets, using the
coverage states of ``spec-coverage`` (SR-05-017):

* **xfail-only** — every test marked for the requirement is held by a strict
  ``xfail`` or a skip, so a test shows ``main`` does not yet meet it. These
  are grouped by the issues the holds cite (SR-05-018).
* **partly met** — some marked tests run and at least one is held, so a test
  shows ``main`` meets part of the requirement and not the rest. These are
  grouped by cited issue too.
* **untested** — no ``@pytest.mark.spec`` marker names it, so no test shows
  ``main`` does it. Nothing is said about whether ``main`` does; these are
  grouped by Requirements Catalog page, in catalog order.

It is a whole-file artifact in the ``docs-site`` flow, so ``uv run docs-site
--check`` fails a fragment that differs from a fresh generation (DF-12-020).
Its inputs are the spec corpus **and the test tree**, so a pull request that
adds a marker or drops an ``xfail`` makes it stale.

Two design points worth not re-deriving:

* **The statement is rendered, never copied.** Each group is a
  ``markdown-exec`` block calling
  :func:`~vultron.metadata.specs.docs_render.requirement_callout` with the
  group's IDs. The page then shows each requirement in the catalog's row
  format, linked to its catalog row and defining no anchor (DF-12-002,
  DF-12-003, DF-12-010), and its prose holds no RFC 2119 keyword (DF-12-004).
  The committed fragment changes only when a requirement's state, catalog page
  or cited issues change, not when a statement is reworded.
* **An empty registry raises.** A report with no ``protocol`` or
  ``foundation`` requirement would generate a page reading "no gaps", which is
  the false pass DF-09-009 forbids.
"""

from __future__ import annotations

from collections.abc import Iterable, Mapping
from pathlib import Path

from vultron.metadata.docs.requirement_catalog import (
    CATALOG_PAGES,
    CatalogPage,
    catalog_location,
)
from vultron.metadata.file_loading import MetadataLoadError
from vultron.metadata.specs.coverage import (
    CoverageState,
    ImplementerCoverageReport,
    RequirementCoverage,
    compute_implementer_coverage,
)
from vultron.metadata.specs.docs_render.rows import ISSUE_URL, issue_links
from vultron.metadata.specs.registry import SpecRegistry

#: ``docs/``-relative path of the page that includes the fragment.
PAGE = "reference/vultron-spec/known-gaps.md"

#: Repository-relative path of the generated fragment.
FRAGMENT_PATH = "docs/reference/vultron-spec/_known-gaps.md"

XFAIL_ONLY_HEADING = "## Requirements a test shows `main` does not yet meet"
PARTLY_MET_HEADING = "## Requirements a test shows `main` meets only in part"
UNTESTED_HEADING = "## Requirements no test checks"

#: The plain label of the untested section (#5976): it reports what the test
#: suite shows, never that the behavior is unbuilt.
UNTESTED_LABEL = "no test shows `main` does this"

_GENERATED_NOTE = (
    "<!-- Generated by `uv run docs-site --write` from the coverage states of "
    "`spec-coverage` (SR-05-017). Do not edit by hand (DF-12-020). -->"
)

_XFAIL_ONLY_INTRO = (
    "Each requirement below has tests, and every one of them is held by a "
    "strict expected failure (`xfail`) or a skip.",
    "So a test shows that `main` does not yet meet the requirement.",
    "The requirements are grouped by the issues that the held tests cite.",
)

_PARTLY_MET_INTRO = (
    "Each requirement below has tests that pass and at least one test that is "
    "held by a strict expected failure (`xfail`) or a skip.",
    "So the tests show that `main` meets part of the requirement, but not all "
    "of it.",
    "The requirements are grouped by the issues that the held tests cite.",
)

_UNTESTED_INTRO = (
    f"For each requirement below, {UNTESTED_LABEL}.",
    "No test is marked for the requirement, so the test suite says nothing "
    "about whether `main` meets it.",
    "It does not mean that `main` lacks the behavior.",
    "The requirements are grouped by their Requirements Catalog page.",
)

_NONE = "No requirement is in this state."

_NO_ISSUE = "No issue cited"


def _callout(spec_ids: Iterable[str]) -> list[str]:
    """A ``markdown-exec`` block printing a callout of *spec_ids* (DF-12-003).

    One ID per line, so two pull requests that move different requirements
    into or out of one group change different lines and do not conflict.
    """
    return [
        '```python exec="true" idprefix=""',
        "from vultron.metadata.specs.docs_render import requirement_callout",
        "print(requirement_callout(",
        *(f'    "{spec_id}",' for spec_id in spec_ids),
        "))",
        "```",
    ]


def _by_issues(
    requirements: Iterable[RequirementCoverage],
) -> dict[tuple[int, ...], list[str]]:
    """Group IDs, sorted, by cited issues; groups citing an issue first, in
    number order."""
    groups: dict[tuple[int, ...], list[str]] = {}
    for requirement in requirements:
        groups.setdefault(requirement.cited_issues, []).append(requirement.id)
    return {
        issues: sorted(ids)
        for issues, ids in sorted(
            groups.items(), key=lambda item: (not item[0], item[0])
        )
    }


def _by_catalog_page(
    spec_ids: Iterable[str],
    registry: SpecRegistry,
    pages: tuple[CatalogPage, ...],
) -> dict[CatalogPage, list[str]]:
    """Group IDs by their catalog page, in placement-table order.

    Raises:
        NotInCatalogError: If an ID's file is on no catalog page (DF-12-015).
    """
    groups: dict[CatalogPage, list[str]] = {page: [] for page in pages}
    for spec_id in spec_ids:
        groups[catalog_location(spec_id, registry, pages).page].append(spec_id)
    return {page: sorted(ids) for page, ids in groups.items() if ids}


def _section(
    heading: str,
    intro: Iterable[str],
    groups: Mapping[str, list[str]],
) -> list[str]:
    lines = [heading, "", *intro, ""]
    if not groups:
        return [*lines, _NONE, ""]
    for subheading, spec_ids in groups.items():
        lines += [f"### {subheading}", "", *_callout(spec_ids), ""]
    return lines


def _held_groups(
    report: ImplementerCoverageReport,
    state: CoverageState,
    registry: SpecRegistry,
    pages: tuple[CatalogPage, ...],
) -> dict[str, list[str]]:
    """The *state* IDs grouped under a subheading naming their cited issues.

    Raises:
        NotInCatalogError: If a listed requirement's file is on no catalog
            page (DF-12-015).
    """
    held = [r for r in report.requirements if r.state is state]
    # Each listed ID is printed by a callout, which refuses an uncatalogued
    # one at build time (DF-12-012); refuse it here too, so the generator,
    # not a later mkdocs build, reports it.
    for requirement in held:
        catalog_location(requirement.id, registry, pages)
    return {
        (f"Tracked by {issue_links(issues)}" if issues else _NO_ISSUE): ids
        for issues, ids in _by_issues(held).items()
    }


def render_fragment(
    report: ImplementerCoverageReport,
    registry: SpecRegistry,
    pages: tuple[CatalogPage, ...] = CATALOG_PAGES,
) -> str:
    """Render the known-gaps fragment from *report* (DF-12-019).

    Args:
        report: Every ``protocol`` and ``foundation`` requirement's state.
        registry: The registry *report* was computed from, for each
            untested requirement's catalog page.
        pages: The placement table.

    Raises:
        MetadataLoadError: If *report* holds no requirement (DF-09-009).
        NotInCatalogError: If a listed requirement's file is on no catalog
            page (DF-12-015).
    """
    if not report.requirements:
        raise MetadataLoadError(
            "the coverage report holds no protocol or foundation requirement, "
            "so the known-gaps page would read as no gaps (DF-09-009)",
            path=FRAGMENT_PATH,
        )
    xfail_groups = _held_groups(
        report, CoverageState.XFAIL_ONLY, registry, pages
    )
    partly_met_groups = _held_groups(
        report, CoverageState.PARTLY_MET, registry, pages
    )
    untested_groups = {
        page.title: ids
        for page, ids in _by_catalog_page(
            report.untested, registry, pages
        ).items()
    }
    lines = [
        _GENERATED_NOTE,
        "",
        *_section(XFAIL_ONLY_HEADING, _XFAIL_ONLY_INTRO, xfail_groups),
        *_section(PARTLY_MET_HEADING, _PARTLY_MET_INTRO, partly_met_groups),
        *_section(UNTESTED_HEADING, _UNTESTED_INTRO, untested_groups),
    ]
    return "\n".join(lines).rstrip("\n") + "\n"


def known_gaps_fragment(root: Path, registry: SpecRegistry) -> str:
    """Render the fragment for the checkout at *root*.

    Args:
        root: The repository root; its ``test/`` tree is scanned for markers.
        registry: The requirement registry loaded from *root*'s ``specs/``.
    """
    report = compute_implementer_coverage(registry, root / "test")
    return render_fragment(report, registry)


