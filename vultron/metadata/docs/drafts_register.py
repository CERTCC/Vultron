"""Load the Protocol Specification's drafts register and render its fragments.

Requirements: DOCBW-08-001 to DOCBW-08-008 in ``specs/docs-build-workflow.yaml``
(ADR-0188).

The register, :data:`REGISTER_PATH`, is the one source of each draft's version,
status, date and, once released, the ``v*`` tag of the release that carries
it. Three readers share :func:`load_register` and :func:`load_register_at`:

* the ``docs-site`` flow renders the status box (:data:`STATUS_BOX_PATH`) and
  one Revision Log status table per draft (:func:`fragment_path`) from it, so
  ``docs-site --check`` fails a fragment that has drifted (DOCBW-08-004/005);
* ``drafts-register check-releases`` compares the register with the register
  at every ``v*`` tag (DOCBW-08-003);
* the promote and the deploy read which draft is the current work in progress
  and which drafts are released, by which tag, through
  :class:`DraftsRegister` or ``drafts-register show`` (JSON).

A malformed register is refused whole, every fault named at its entry's
``path:line:col`` through :mod:`vultron.metadata.file_loading` (DOCBW-08-002,
MS-17).

CLI (``uv run drafts-register``)::

    drafts-register show [--ref REF]   # the register as JSON
    drafts-register check-releases     # exit 1 if a released entry and its
                                       # tag's register disagree
"""

