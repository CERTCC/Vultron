#: The register, repository-relative (DOCBW-08-001).
REGISTER_PATH = "docs/reference/vultron-spec/drafts.yaml"

#: The status box every Protocol Specification page includes (DOCBW-08-004).
STATUS_BOX_PATH = "docs/reference/vultron-spec/_status.md"

#: The Revision Log, which includes one status table per draft.
REVISION_LOG_PATH = "docs/reference/vultron-spec/revision-log.md"

#: The directory of the per-draft status tables. Listed in ``exclude_docs``:
#: a table reaches a reader only through the Revision Log's include line, and
#: its frozen-copy link is written relative to the Revision Log, not to it.
FRAGMENT_DIR = "docs/reference/vultron-spec/_drafts"

#: The label of the specification while an unreleased draft is open
#: (DOCBW-08-006).
CURRENT_DRAFT_LABEL = "Current draft (work in progress)"

#: The site directory a released draft's frozen copy is served under
#: (DOCBW-08-008): ``spec/draft-N/``.
FROZEN_COPY_DIR = "spec"

_GENERATED_NOTE = (
    "<!-- Generated by `uv run docs-site --write` from "
    f"`{REGISTER_PATH}`. Do not edit by hand (DOCBW-08-004). -->\n"
)

_ISO_DATE = re.compile(r"\d{4}-\d{2}-\d{2}")


def _iso_date(value: object) -> object:
    """Admit a date only as ``YYYY-MM-DD`` (DOCBW-08-001).

    PyYAML reads an unquoted ``2026-11-06`` as a :class:`date` and a quoted
    one as text; both are admitted. A timestamp, a number (which Pydantic
    would read as Unix seconds) or any other text is refused.
    """
    # Pydantic turns only a ValueError into a validation error, so a wrong
    # type is refused with one too.
    if isinstance(value, date) and not isinstance(value, datetime):
        return value
    if isinstance(value, str) and _ISO_DATE.fullmatch(value):
        return value
    raise ValueError("a date in the YYYY-MM-DD format, not a timestamp")


DraftVersion = Annotated[
    str, StringConstraints(pattern=r"^draft-[1-9][0-9]*$")
]
"""``draft-N``, with ``N`` from 1 and no leading zero."""

ReleaseTag = Annotated[
    str, StringConstraints(pattern=r"^v\d{4}\.(?:1[0-2]|[1-9])\.\d+$")
]
"""A ``vYYYY.M.P`` release tag (ADR-0006, DOCBW-07-011)."""

RegisterDate = Annotated[date, BeforeValidator(_iso_date)]


class _Draft(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)

    version: DraftVersion
    date: RegisterDate

    @property
    def number(self) -> int:
        """``N`` of ``draft-N``."""
        return int(self.version.removeprefix("draft-"))


class UnreleasedDraft(_Draft):
    """The draft still open: no release carries it yet."""

    status: Literal["unreleased"]


class ReleasedDraft(_Draft):
    """A draft that the release tagged :attr:`release` carries."""

    status: Literal["released"]
    release: ReleaseTag


DraftEntry = Annotated[
    UnreleasedDraft | ReleasedDraft, Field(discriminator="status")
]


class _RegisterFile(BaseModel):
    model_config = ConfigDict(extra="forbid")

    drafts: list[DraftEntry] = Field(min_length=1)


@dataclass(frozen=True)
class DraftsRegister:
    """A well-formed drafts register, its entries ordered by draft number.

    Attributes:
        drafts: Every entry, ``draft-1`` first.
        shown: Where it was read from, for messages: a repository-relative
            path, or ``REF:path`` for a register read at a git ref.
    """

    drafts: tuple[UnreleasedDraft | ReleasedDraft, ...]
    shown: str

    @property
    def current(self) -> UnreleasedDraft | None:
        """The current draft (work in progress), or ``None`` when all are released."""
        for entry in self.drafts:
            if isinstance(entry, UnreleasedDraft):
                return entry
        return None

    @property
    def released(self) -> tuple[ReleasedDraft, ...]:
        """Every released draft, ``draft-1`` first."""
        return tuple(e for e in self.drafts if isinstance(e, ReleasedDraft))

    @property
    def newest_released(self) -> ReleasedDraft | None:
        """The highest-numbered released draft, or ``None``."""
        released = self.released
        return released[-1] if released else None

    def entry(self, version: str) -> UnreleasedDraft | ReleasedDraft | None:
        """The entry for *version*, or ``None``."""
        for entry in self.drafts:
            if entry.version == version:
                return entry
        return None

    def released_by(self, tag: str) -> ReleasedDraft | None:
        """The draft whose release is *tag*, or ``None`` (at most one, DOCBW-08-002)."""
        for entry in self.released:
            if entry.release == tag:
                return entry
        return None

    def as_json(self) -> dict[str, Any]:
        """The register as the JSON ``drafts-register show`` prints."""
        current = self.current
        return {
            "register": self.shown,
            "current": (
                None
                if current is None
                else {
                    "version": current.version,
                    "date": current.date.isoformat(),
                }
            ),
            "released": [
                {
                    "version": e.version,
                    "date": e.date.isoformat(),
                    "release": e.release,
                }
                for e in self.released
            ],
        }


def _entry_fault(
    detail: str, shown: str, positions: NodePositions, index: int
) -> MetadataLoadError:
    line_col = positions.get(("drafts", index))
    return MetadataLoadError(
        f"{detail} (DOCBW-08-002)",
        path=shown,
        line=None if line_col is None else line_col[0],
        column=None if line_col is None else line_col[1],
    )


def _line(positions: NodePositions, index: int) -> str:
    line_col = positions.get(("drafts", index))
    return "?" if line_col is None else str(line_col[0])


def register_faults(
    entries: Sequence[UnreleasedDraft | ReleasedDraft],
    shown: str,
    positions: NodePositions,
) -> list[MetadataLoadError]:
    """Every DOCBW-08-002 fault across *entries*, each at its entry.

    The schema has already refused a released entry with no tag and an
    unreleased one with a tag; these are the faults between entries.
    """
    faults: list[MetadataLoadError] = []
    first_of: dict[str, int] = {}
    tag_of: dict[str, int] = {}
    first_open: int | None = None
    highest = max(e.number for e in entries)
    for index, entry in enumerate(entries):
        if entry.version in first_of:
            faults.append(
                _entry_fault(
                    f"duplicate version {entry.version}: it is also at line "
                    f"{_line(positions, first_of[entry.version])}",
                    shown,
                    positions,
                    index,
                )
            )
        else:
            first_of[entry.version] = index
        if isinstance(entry, ReleasedDraft):
            if entry.release in tag_of:
                other = entries[tag_of[entry.release]]
                faults.append(
                    _entry_fault(
                        f"{entry.version} names release {entry.release}, "
                        f"which {other.version} at line "
                        f"{_line(positions, tag_of[entry.release])} names "
                        "too: one release carries one draft",
                        shown,
                        positions,
                        index,
                    )
                )
            else:
                tag_of[entry.release] = index
            continue
        if first_open is not None:
            faults.append(
                _entry_fault(
                    f"{entry.version} is unreleased, and so is "
                    f"{entries[first_open].version} at line "
                    f"{_line(positions, first_open)}: at most one draft is "
                    "unreleased",
                    shown,
                    positions,
                    index,
                )
            )
        else:
            first_open = index
        if entry.number < highest:
            faults.append(
                _entry_fault(
                    f"{entry.version} is unreleased but draft-{highest} is "
                    "newer: only the highest-numbered draft can be unreleased",
                    shown,
                    positions,
                    index,
                )
            )
    numbers = sorted({e.number for e in entries})
    expected = 1
    for number in numbers:
        if number != expected:
            missing = ", ".join(f"draft-{n}" for n in range(expected, number))
            index = next(
                i for i, e in enumerate(entries) if e.number == number
            )
            faults.append(
                _entry_fault(
                    f"{missing} missing before draft-{number}: the drafts "
                    "are numbered from draft-1 with no gap",
                    shown,
                    positions,
                    index,
                )
            )
        expected = number + 1
    return faults


def parse_register(text: str, shown: str) -> DraftsRegister:
    """Parse and check register *text*, naming faults after *shown*.

    Raises:
        MetadataLoadError: When the text is not YAML, or an entry breaks the
            schema (DOCBW-08-001): an unknown field, a bad version, status,
            date or tag, a released entry with no tag, an unreleased entry
            with a tag, or no entries at all.
        MetadataLoadErrors: When entries conflict (DOCBW-08-002), every
            conflict listed.
    """
    shown_path = Path(shown)
    data = loads_yaml(text, shown_path)
    positions = yaml_node_positions(text)
    parsed = validate(
        _RegisterFile,
        data,
        path=shown_path,
        prefix="malformed drafts register entry (DOCBW-08-001)",
        positions=positions,
    )
    collector = FailureCollector()
    collector.failures.extend(register_faults(parsed.drafts, shown, positions))
    collector.raise_if_any(
        summary=f"{shown}: the drafts register is malformed (DOCBW-08-002):"
    )
    return DraftsRegister(
        drafts=tuple(sorted(parsed.drafts, key=lambda e: e.number)),
        shown=shown,
    )


def load_register(root: Path | None = None) -> DraftsRegister:
    """Load the committed register under *root* (the repository by default).

    Raises:
        MetadataLoadError, MetadataLoadErrors: As :func:`parse_register`.
        FileNotFoundError: When the register does not exist.
    """
    base = root or repo_root()
    path = base / REGISTER_PATH
    shown = display_path(path, base)
    return parse_register(read_utf8(path, shown), shown)


def load_register_at(
    ref: str, root: Path | None = None, *, git: GitRunner | None = None
) -> DraftsRegister | None:
    """Load the register as *ref* holds it, or ``None`` when *ref* has none.

    A ref older than the register holds none. Faults are named
    ``REF:path:line:col``.

    Raises:
        MetadataLoadError, MetadataLoadErrors: As :func:`parse_register`.
        GitError: When git cannot read *ref*.
    """
    run = git or git_runner(root or repo_root())
    if not run(["ls-tree", "--name-only", ref, "--", REGISTER_PATH]).strip():
        return None
    text = run(["show", f"{ref}:{REGISTER_PATH}"])
    return parse_register(text, f"{ref}:{REGISTER_PATH}")


# --- Generated fragments (DOCBW-08-004 to DOCBW-08-008) ---------------------


def fragment_path(version: str) -> str:
    """The repository-relative path of *version*'s Revision Log status table."""
    return f"{FRAGMENT_DIR}/{version}.md"


def include_line(version: str) -> str:
    """The Revision Log line that includes *version*'s status table.

    ``rewrite-relative-urls=false`` keeps the frozen-copy link as written: it
    is relative to the Revision Log's built URL, not to the fragment.
    """
    return (
        f'{{% include-markdown "./_drafts/{version}.md" '
        "rewrite-relative-urls=false %}"
    )


def frozen_copy_url(version: str) -> str:
    """The URL of *version*'s frozen copy, relative to the built Revision Log.

    The frozen copy is served at ``spec/draft-N/`` (DOCBW-08-008), outside
    ``docs/``, so MkDocs cannot resolve the link: it keeps it as written.
    """
    page = url_path(REVISION_LOG_PATH)
    return posixpath.relpath(f"{FROZEN_COPY_DIR}/{version}", page) + "/"


def _status_text(entry: UnreleasedDraft | ReleasedDraft) -> str:
    if isinstance(entry, ReleasedDraft):
        return f"Released in `{entry.release}`"
    return f"{CURRENT_DRAFT_LABEL}, not yet released"


def _table(
    entry: UnreleasedDraft | ReleasedDraft, *, indent: str = ""
) -> list[str]:
    rows = [
        "| Property | Value |",
        "|----------|-------|",
        f"| Version | `{entry.version}` |",
        f"| Status | {_status_text(entry)} |",
        f"| Date | {entry.date.isoformat()} |",
    ]
    return [f"{indent}{row}" for row in rows]


def render_draft_table(entry: UnreleasedDraft | ReleasedDraft) -> str:
    """The Revision Log status table of *entry* (DOCBW-08-004, DOCBW-08-008).

    A released draft's table links its frozen copy.
    """
    rows = _table(entry)
    if isinstance(entry, ReleasedDraft):
        rows.append(
            f"| Frozen copy | [`spec/{entry.version}/`]"
            f"({frozen_copy_url(entry.version)}) |"
        )
    return _GENERATED_NOTE + "\n" + "\n".join(rows) + "\n"


def _citation(entry: UnreleasedDraft | ReleasedDraft) -> str:
    base = f"Vultron Protocol Specification, `{entry.version}`, {entry.date.isoformat()}"
    if isinstance(entry, ReleasedDraft):
        return f"{base}, `{entry.release}`"
    return base


def _open_draft_text(
    current: UnreleasedDraft, newest: ReleasedDraft | None
) -> list[str]:
    text = [
        "Until a release of the Vultron repository carries the draft, its "
        "text can still change.",
        "To cite this text, name the specification, the version and the "
        f"date, for example: {_citation(current)}.",
        "Until a release carries the draft, also name the "
        "`publish-YYYY-MM-DD.N` tag in the page footer, which identifies the "
        "text you read ([Vultron Release Versioning](../versioning.md)).",
        "Once a release carries the draft, name the release tag that the "
        "Revision Log gives for it instead.",
    ]
    if newest is not None:
        text.append(
            f"The newest released draft is `{newest.version}`, which release "
            f"`{newest.release}` carries; the Revision Log links its frozen "
            "copy."
        )
    return text


def _released_draft_text(newest: ReleasedDraft) -> list[str]:
    return [
        f"Release `{newest.release}` of the Vultron repository carries this "
        "draft, so its text no longer changes: a change goes into the next "
        "draft.",
        "To cite this text, name the specification, the version, the date "
        f"and the release tag, for example: {_citation(newest)}.",
    ]


def render_status_box(register: DraftsRegister) -> str:
    """The status box (DOCBW-08-004, DOCBW-08-006, DOCBW-08-007).

    While a draft is unreleased, the box labels the specification
    :data:`CURRENT_DRAFT_LABEL`. Once every draft is released, it names the
    newest released draft and its release tag, and carries no such label.
    """
    current = register.current
    newest = register.newest_released
    entry: UnreleasedDraft | ReleasedDraft
    if current is not None:
        entry = current
        title = f"{CURRENT_DRAFT_LABEL}: Draft {current.number}"
        tail = _open_draft_text(current, newest)
    else:
        # A register holds at least one entry, and none is unreleased.
        assert newest is not None
        entry = newest
        title = (
            f"Status: Draft {newest.number}, released in `{newest.release}`"
        )
        tail = _released_draft_text(newest)
    body = [
        "This specification is a draft, not a finished standard.",
        "",
        *_table(entry),
        "",
        "The date is the day the entry for this draft was added to the "
        "[Revision Log](revision-log.md).",
        *tail,
    ]
    lines = [f'!!! note "{title}"', ""]
    lines += [f"    {line}" if line else "" for line in body]
    return _GENERATED_NOTE + "\n" + "\n".join(lines) + "\n"


def desired_fragments(register: DraftsRegister) -> dict[str, str]:
    """``{repo-relative path: contents}`` of every fragment of *register*."""
    contents = {STATUS_BOX_PATH: render_status_box(register)}
    for entry in register.drafts:
        contents[fragment_path(entry.version)] = render_draft_table(entry)
    return contents


_DRAFT_INCLUDE = re.compile(r"_drafts/")


def revision_log_faults(
    root: Path, register: DraftsRegister
) -> list[MetadataLoadError]:
    """Faults in the Revision Log's include lines for the status tables.

    The Revision Log includes each draft's table once, newest first, through
    :func:`include_line`, and no table of a draft the register lacks; a
    released draft whose table is not included would leave its frozen copy
    unlinked (DOCBW-08-008). The page's prose is hand-written, so a fault here
    is fixed by hand: nothing is written for it.
    """
    path = root / REVISION_LOG_PATH
    shown = display_path(path, root)
    text = read_utf8(path, shown)
    wanted = {include_line(e.version): e.version for e in register.drafts}
    found: list[tuple[int, str]] = []
    faults: list[MetadataLoadError] = []
    for number, line in enumerate(text.splitlines(), start=1):
        if "include-markdown" not in line or not _DRAFT_INCLUDE.search(line):
            continue
        version = wanted.get(line.strip())
        if version is None:
            faults.append(
                MetadataLoadError(
                    "a status-table include that names no draft in the "
                    f"register, or is not written as {include_line('draft-N')!r}"
                    " (DOCBW-08-004)",
                    path=shown,
                    line=number,
                )
            )
            continue
        if any(v == version for _n, v in found):
            faults.append(
                MetadataLoadError(
                    f"{version}'s status table is included twice (DOCBW-08-004)",
                    path=shown,
                    line=number,
                )
            )
            continue
        found.append((number, version))
    included = {v for _n, v in found}
    for entry in register.drafts:
        if entry.version not in included:
            faults.append(
                MetadataLoadError(
                    f"{entry.version} has no section: add one with the line "
                    f"{include_line(entry.version)!r} (DOCBW-08-004, "
                    "DOCBW-08-008)",
                    path=shown,
                )
            )
    order = [int(v.removeprefix("draft-")) for _n, v in found]
    if order != sorted(order, reverse=True):
        faults.append(
            MetadataLoadError(
                "the drafts' status tables are not newest first",
                path=shown,
                line=found[0][0],
            )
        )
    return faults


# --- Release tags (DOCBW-08-003) ---------------------------------------------


def release_tags(git: GitRunner) -> list[str]:
    """Every ``v*`` tag in the clone, in git's order."""
    return git(["tag", "--list", "v*"]).split()


def release_faults(
    register: DraftsRegister,
    tags: Sequence[str],
    register_at: Callable[[str], DraftsRegister | None],
) -> list[str]:
    """Where *register* and the register at a ``v*`` tag disagree (DOCBW-08-003).

    Args:
        register: The register at the checked-out commit.
        tags: Every ``v*`` tag.
        register_at: Returns the register a tag holds, or ``None``.

    A fault is reported when a tag's register names a draft released by that
    tag and *register* lacks that entry or holds a different one, or when
    *register* names an existing tag as a draft's release and that tag's
    register lacks the same entry. A released entry whose tag does not exist
    yet is not judged: it waits for the promote that makes the tag.
    """
    faults: list[str] = []
    existing = set(tags)
    at: dict[str, DraftsRegister | None] = {}
    for tag in tags:
        at[tag] = tagged = register_at(tag)
        if tagged is None:
            continue
        carried = tagged.released_by(tag)
        if carried is None:
            continue
        here = register.entry(carried.version)
        if here is None:
            faults.append(
                f"{register.shown}: {carried.version} is missing; release "
                f"{tag}'s register gives it as released by {tag}, and a "
                "released entry never changes"
            )
        elif here != carried:
            faults.append(
                f"{register.shown}: {carried.version} differs from its entry "
                f"at release {tag} ({_describe(carried)}): a released entry "
                "never changes"
            )
    for entry in register.released:
        if entry.release not in existing:
            continue
        tagged = at[entry.release]
        theirs = None if tagged is None else tagged.entry(entry.version)
        if theirs != entry:
            faults.append(
                f"{register.shown}: {entry.version} names release "
                f"{entry.release}, but that tag's register "
                + (
                    "does not exist"
                    if tagged is None
                    else "does not hold the same entry"
                )
                + ": an existing release cannot take a draft it never carried"
            )
    return faults


def _describe(entry: UnreleasedDraft | ReleasedDraft) -> str:
    text = f"{entry.status}, {entry.date.isoformat()}"
    if isinstance(entry, ReleasedDraft):
        text += f", {entry.release}"
    return text


def check_releases(root: Path, git: GitRunner | None = None) -> list[str]:
    """Run the DOCBW-08-003 check on the checkout at *root*; return its faults.

    Raises:
        MetadataLoadError, MetadataLoadErrors: When a register is malformed.
        GitError: When git cannot read a tag.
    """
    run = git or git_runner(root)
    register = load_register(root)
    return release_faults(
        register,
        release_tags(run),
        lambda tag: load_register_at(tag, root, git=run),
    )


def main(argv: list[str] | None = None) -> None:
    """CLI entry point: ``uv run drafts-register {show,check-releases}``."""
    parser = argparse.ArgumentParser(
        description="Read the Protocol Specification's drafts register."
    )
    commands = parser.add_subparsers(dest="command", required=True)
    show = commands.add_parser(
        "show",
        help="Print the current draft and the released drafts as JSON.",
    )
    show.add_argument(
        "--ref",
        help="Read the register as this git ref holds it, not the checkout.",
    )
    commands.add_parser(
        "check-releases",
        help=(
            "Exit 1 if a released entry and the register at its release tag "
            "disagree (DOCBW-08-003)."
        ),
    )
    args = parser.parse_args(argv)
    root = repo_root()
    try:
        if args.command == "show":
            register = (
                load_register(root)
                if args.ref is None
                else load_register_at(args.ref, root)
            )
            if register is None:
                print(
                    f"[ERROR] {args.ref} holds no {REGISTER_PATH}",
                    file=sys.stderr,
                )
                sys.exit(1)
            print(json.dumps(register.as_json(), indent=2))
            return
        faults = check_releases(root)
    except (GitError, OSError, ValueError) as exc:
        print(f"[ERROR] {exc}", file=sys.stderr)
